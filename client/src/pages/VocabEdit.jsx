import { useNavigate, useParams, Link } from 'react-router-dom';
import { ArrowLeft } from 'lucide-react';
import { api } from '../api/client.js';
import { useAsync } from '../hooks/useAsync.js';
import { ErrorBanner, PageHeader, PageSkeleton } from '../components/ui.jsx';
import VocabForm from '../components/VocabForm.jsx';

export default function VocabEdit() {
  const { id } = useParams(); const nav = useNavigate();
  const { data, loading, error, reload } = useAsync(async () => (await api.get(`/vocabulary/${id}`)).data.entry, [id]);
  if (loading) return <PageSkeleton label="Loading the entry…" />;
  if (error) return <ErrorBanner error={error} onRetry={reload} />;
  return (
    <>
      <Link to={`/words/${id}`} className="btn-ghost mb-3 !min-h-8 !px-2 !text-xs"><ArrowLeft className="h-3.5 w-3.5" aria-hidden="true" />Back to entry</Link>
      <PageHeader
        eyebrow="Refine the entry"
        title={`Edit “${data.word}”`}
        sub={data.source === 'ai' ? 'Generated by AI — corrections you save are kept.' : 'Adjust any detail. Nothing changes until you save.'}
      />
      <VocabForm initial={data} submitLabel="Save changes" onSubmit={async (p) => { await api.patch(`/vocabulary/${id}`, p); nav(`/words/${id}`); }} />
    </>
  );
}
